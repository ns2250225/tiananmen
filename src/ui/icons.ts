export type IconName = keyof typeof I;

export function icon(name: IconName, px = 2, cls = ''): string {
  const g = I[name];
  const rects: string[] = [];
  for (let y = 0; y < g.length; y++) {
    let x = 0;
    while (x < g[y].length) {
      if (g[y][x] === '#') {
        let w = 1;
        while (g[y][x + w] === '#') w++;
        rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1"/>`);
        x += w;
      } else x++;
    }
  }
  return `<svg class="ico ${cls}" width="${12 * px}" height="${12 * px}" viewBox="0 0 12 12" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects.join('')}</svg>`;
}
